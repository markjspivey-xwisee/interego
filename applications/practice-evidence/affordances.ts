const hints = (title: string, readOnly: boolean, destructive: boolean, idempotent: boolean, openWorld: boolean): Affordance['annotations'] => ({
  title, readOnlyHint: readOnly, destructiveHint: destructive, idempotentHint: idempotent, openWorldHint: openWorld,
});

const out = (description: string, names: readonly string[]): Affordance['outputs'] => ({
  description,
  properties: Object.fromEntries(names.map((n) => [n, { type: 'string' as const }])),
});

