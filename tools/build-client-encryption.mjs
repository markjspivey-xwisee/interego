/** Build the shared client encryption UI into the self-contained MCP App. */
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = await build({
  absWorkingDir: root, preserveSymlinks: true,
  entryPoints: [join(root, 'deploy/mcp-relay/client/encryption-ui.ts')],
  bundle: true, platform: 'browser', format: 'iife', globalName: 'InteregoPrivateContent',
  target: 'es2022', write: false, sourcemap: false, legalComments: 'inline', minify: false,
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const generated = '// Generated by tools/build-client-encryption.mjs. Do not edit.\n'
  + 'export const CLIENT_ENCRYPTION_UI_JS = ' + JSON.stringify(js) + ';\n';
const target = join(root, 'deploy/mcp-relay/client-encryption-bundle.ts');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) throw new Error('Client encryption bundle is stale. Run node tools/build-client-encryption.mjs.');
  console.log('Client encryption bundle matches its source.');
} else {
  writeFileSync(target, generated);
  console.log(`Built client encryption bundle (${js.length} bytes).`);
}
